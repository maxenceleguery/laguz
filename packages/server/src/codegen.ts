import {
  isEnumType,
  isInputObjectType,
  isInterfaceType,
  isListType,
  isNonNullType,
  isObjectType,
  isScalarType,
  isUnionType,
  type GraphQLArgument,
  type GraphQLField,
  type GraphQLInputField,
  type GraphQLInputType,
  type GraphQLNamedType,
  type GraphQLOutputType,
  type GraphQLSchema,
} from "graphql";

export type TypesOptions = {
  /** TypeScript types for custom scalars, e.g. `{ DateTime: "string" }`. Others are `unknown`. */
  scalars?: Record<string, string>;
};

const OUTPUT_SCALARS: Record<string, string> = {
  ID: "string",
  String: "string",
  Int: "number",
  Float: "number",
  Boolean: "boolean",
};
// IDs are serialized as strings but accept integers as input.
const INPUT_SCALARS: Record<string, string> = { ...OUTPUT_SCALARS, ID: "string | number" };

/**
 * TypeScript types for a schema, for `createPool<Schema>(fetcher)` in
 * `@laguzjs/client`. Object types become interfaces, fields with arguments
 * become methods, enums become string unions (and `EnumValue` in arguments).
 */
export function generateTypes(schema: GraphQLSchema, options: TypesOptions = {}): string {
  const query = schema.getQueryType();
  if (!query) throw new Error("the schema has no query type");
  const scalar = (name: string, builtin: Record<string, string>) =>
    builtin[name] ?? options.scalars?.[name] ?? "unknown";
  let usesEnumValue = false;

  const nullable = (type: string, isNullable: boolean) => (isNullable ? `${type} | null` : type);
  const list = (item: string) => (item.includes(" | ") ? `(${item})[]` : `${item}[]`);

  function output(type: GraphQLOutputType, isNullable = true): string {
    if (isNonNullType(type)) return output(type.ofType, false);
    if (isListType(type)) return nullable(list(output(type.ofType)), isNullable);
    return nullable(isScalarType(type) ? scalar(type.name, OUTPUT_SCALARS) : type.name, isNullable);
  }

  function input(type: GraphQLInputType, isNullable = true): string {
    if (isNonNullType(type)) return input(type.ofType, false);
    if (isListType(type)) return nullable(list(input(type.ofType)), isNullable);
    if (isScalarType(type)) return nullable(scalar(type.name, INPUT_SCALARS), isNullable);
    if (isEnumType(type)) {
      usesEnumValue = true;
      return nullable(`EnumValue<${type.name}>`, isNullable);
    }
    return nullable(type.name, isNullable);
  }

  const optional = (arg: GraphQLArgument | GraphQLInputField) =>
    !isNonNullType(arg.type) || arg.defaultValue !== undefined;
  const property = (arg: GraphQLArgument | GraphQLInputField) =>
    `${arg.name}${optional(arg) ? "?" : ""}: ${input(arg.type)}`;

  function field(f: GraphQLField<unknown, unknown>): string {
    const type = output(f.type);
    if (!f.args.length) return `${f.name}: ${type};`;
    const all = f.args.every(optional) ? "?" : "";
    return `${f.name}(args${all}: { ${f.args.map(property).join("; ")} }): ${type};`;
  }

  const comment = (text: string | null | undefined, indent = "") =>
    text
      ? `${indent}/** ${text.replaceAll("*/", "* /").replaceAll("\n", `\n${indent} * `)} */\n`
      : "";

  function declaration(type: GraphQLNamedType): string | undefined {
    const doc = comment(type.description);
    if (isObjectType(type) || isInterfaceType(type)) {
      const fields = Object.values(type.getFields())
        .map((f) => `${comment(f.description, "  ")}  ${field(f)}`)
        .join("\n");
      return `${doc}export interface ${type.name} {\n${fields}\n}`;
    }
    if (isUnionType(type)) {
      return `${doc}export type ${type.name} = ${type
        .getTypes()
        .map((t) => t.name)
        .join(" | ")};`;
    }
    if (isEnumType(type)) {
      const values = type.getValues().map((v) => JSON.stringify(v.name));
      return `${doc}export type ${type.name} = ${values.join(" | ")};`;
    }
    if (isInputObjectType(type)) {
      const fields = Object.values(type.getFields())
        .map((f) => `${comment(f.description, "  ")}  ${property(f)};`)
        .join("\n");
      return `${doc}export interface ${type.name} {\n${fields}\n}`;
    }
  }

  const named = Object.values(schema.getTypeMap())
    .filter((t) => !t.name.startsWith("__") && !isScalarType(t))
    .sort((a, b) => (a === query ? -1 : b === query ? 1 : a.name.localeCompare(b.name)));
  const body = named.map(declaration).filter(Boolean).join("\n\n");

  return [
    "// Generated by laguz-types. Do not edit.",
    usesEnumValue ? 'import type { EnumValue } from "@laguzjs/client";\n' : "",
    `export interface Schema {\n  Query: ${query.name};\n}\n`,
    `${body}\n`,
  ]
    .filter(Boolean)
    .join("\n");
}
