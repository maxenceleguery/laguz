// Pagination and dependent-query benchmark: TanStack Query vs laguz, real
// Chromium, brotli, h2 + HTTP/1.1, 4G + slow 4G. Writes docs/benchmarks/features.md.
//   bun bench/features.ts      (REPS=5 by default)
import { writeFileSync } from "node:fs";
import { launch } from "./cdp";
import { counters, reset } from "./schema";
import { link, startTls } from "./server";

const REPS = Number(process.env.REPS ?? 5);
const THINK_MS = 500; // user reads the page before asking for more
const NETWORKS = {
  "4g": { rtt: 50, down: 10e6, up: 5e6 },
  "slow-4g": { rtt: 150, down: 1.6e6, up: 0.75e6 },
} as const;
const PROTOCOLS = { "http/1.1": ["--disable-http2"], h2: [] } as const;
const server = await startTls();
link.encoding = "br";

type Browser = Awaited<ReturnType<typeof launch>>;
const median = (xs: number[]) => {
  const s = [...xs].sort((a, b) => a - b);
  return s.length % 2 ? s[s.length >> 1]! : (s[s.length / 2 - 1]! + s[s.length / 2]!) / 2;
};

async function open(browser: Browser, network: keyof typeof NETWORKS, view: string, mode: string) {
  const tab = await browser.tab();
  await tab.s("Page.enable");
  await tab.s("Network.enable");
  await tab.s("Network.setCacheDisabled", { cacheDisabled: true });
  const n = NETWORKS[network];
  await tab.s("Network.emulateNetworkConditions", {
    offline: false,
    latency: 0,
    downloadThroughput: n.down / 8,
    uploadThroughput: n.up / 8,
  });
  link.rttMs = n.rtt;
  reset();
  const loaded = tab.once("Page.loadEventFired");
  await tab.s("Page.navigate", {
    url: `https://localhost:${server.port}/?view=${view}&mode=${mode}`,
  });
  await loaded;
  await tab.evaluate("__ready");
  return tab;
}
const phase = async <T>(f: () => Promise<T>) => {
  counters.requests = 0;
  counters.dbCalls = 0;
  const out = await f();
  return { out, requests: counters.requests, db: counters.dbCalls };
};

async function feed(b: Browser, network: keyof typeof NETWORKS, mode: string) {
  const tab = await open(b, network, "feed", mode);
  const more = await phase(async () => {
    const ms: number[] = [];
    for (let i = 0; i < 4; i++) {
      await Bun.sleep(THINK_MS);
      ms.push(await tab.evaluate("__loadMore()"));
    }
    return ms;
  });
  const refresh = await phase(() => tab.evaluate("__refresh()"));
  await tab.close();
  return {
    loadMoreMs: median(more.out),
    loadMoreRequests: more.requests,
    loadMoreDb: more.db,
    refreshMs: refresh.out.settledMs,
    refreshRequests: refresh.requests,
    refreshDb: refresh.db,
  };
}

async function chain(b: Browser, network: keyof typeof NETWORKS, mode: string) {
  const tab = await open(b, network, "chain", mode);
  const nav = await phase(() => tab.evaluate("__nav()"));
  await tab.close();
  return { leadMs: nav.out.last, requests: nav.requests, db: nav.db };
}

const rows: { kind: string; key: string; r: Record<string, number> }[] = [];
for (const [protocol, flags] of Object.entries(PROTOCOLS)) {
  const browser = await launch(
    `${import.meta.dir}/.tmp/chrome-features-${protocol.replace("/", "")}`,
    ["--ignore-certificate-errors", ...flags],
  );
  for (const network of Object.keys(NETWORKS) as (keyof typeof NETWORKS)[]) {
    for (const [kind, run, modes] of [
      ["feed", feed, ["tanstack", "pool-stream", "pool-prefetch"]],
      ["chain", chain, ["tanstack", "pool-stream", "pool-refs"]],
    ] as const) {
      for (const mode of modes) await run(browser, network, mode); // warm-up
      for (let rep = 0; rep < REPS; rep++)
        for (const mode of modes) {
          const r = await run(browser, network, mode);
          rows.push({ kind, key: `${protocol}|${network}|${mode}`, r });
          console.log(kind, protocol, network, mode, rep, JSON.stringify(r));
        }
    }
  }
  browser.close();
}
server.close();

const table = (kind: string, cols: [string, string][]) => {
  const groups = Map.groupBy(
    rows.filter((x) => x.kind === kind),
    (x) => x.key,
  );
  return [
    `| protocol | network | mode | ${cols.map(([, h]) => h).join(" | ")} |`,
    `|---|---|---|${cols.map(() => "---:").join("|")}|`,
    ...[...groups].map(
      ([k, rs]) =>
        `| ${k.split("|").join(" | ")} | ${cols.map(([c]) => Math.round(median(rs.map((x) => x.r[c]!)))).join(" | ")} |`,
    ),
  ].join("\n");
};
const out = `# Benchmark: pagination and dependent queries

Generated by \`bun bench/features.ts\` on ${new Date().toISOString().slice(0, 10)}. Same setup as dashboard.md (real Chromium,
production React, RTT added server-side, bandwidth via CDP), brotli on, ${REPS} runs per cell, medians.

## Infinite feed (cursor pagination, 10 items per page)

First page, then 4 x "load more" with ${THINK_MS} ms of reading between clicks, then a refresh of the 5 loaded pages.
TanStack: \`useInfiniteQuery\`. laguz: \`useInfiniteData\`, without and with \`prefetch: 1\`.

${table("feed", [
  ["loadMoreMs", "load more ms (median)"],
  ["loadMoreRequests", "load more requests"],
  ["loadMoreDb", "load more DB"],
  ["refreshMs", "refresh ms"],
  ["refreshRequests", "refresh requests"],
  ["refreshDb", "refresh DB"],
])}

## Dependent queries (user -> team -> team lead), cold in-app navigation

TanStack: three \`useQuery\` chained with \`enabled\`. laguz: one \`useData\` with nested \`ref()\` args,
resolved on the client (pool-stream) or forwarded by the server (pool-refs).

${table("chain", [
  ["leadMs", "lead visible ms"],
  ["requests", "requests"],
  ["db", "DB calls"],
])}
`;
writeFileSync(`${import.meta.dir}/../docs/benchmarks/features.md`, out);
console.log(out);
process.exit(0);
